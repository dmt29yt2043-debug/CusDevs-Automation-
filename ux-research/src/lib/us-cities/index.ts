export type CitySize = "Megacity" | "Large city" | "Major city" | "City" | "Town";

export function getCitySize(pop: number): CitySize {
  if (pop >= 1_000_000) return "Megacity";
  if (pop >= 300_000)   return "Large city";
  if (pop >= 100_000)   return "Major city";
  if (pop >= 30_000)    return "City";
  return "Town";
}

export function searchCities(query: string, limit = 7): USCity[] {
  if (!query || query.length < 2) return [];
  const q = query.toLowerCase().trim();

  // Deduplicate by city+state key first
  const seen = new Set<string>();
  const unique = US_CITIES.filter((c) => {
    const key = `${c.city}|${c.state}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });

  // Match: city starts with query OR any word in city name starts with query
  return unique
    .filter((c) => {
      const name = c.city.toLowerCase();
      return name.startsWith(q) || name.split(" ").some((w) => w.startsWith(q));
    })
    .sort((a, b) => b.pop - a.pop)
    .slice(0, limit);
}
